"""Simple addition utility.

This repository is primarily a React Tic Tac Toe app, but this file is added per request.
"""

from __future__ import annotations


# PUBLIC_INTERFACE
def add(a: float, b: float) -> float:
    """Return the sum of two numbers.

    Args:
        a: First number.
        b: Second number.

    Returns:
        The numeric sum of a and b.
    """
    return a + b
